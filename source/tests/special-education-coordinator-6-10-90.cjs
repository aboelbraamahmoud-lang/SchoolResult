assert.ok(!special.includes('المنسق العام للمادة'),'normal subject coordinator cannot leak into support report');
const unassigned=strings(ctx.N9({workspace:ws,subject:'التربية الإسلامية',supportLevel:true,supportCoordinatorName:''}));
assert.ok(!unassigned.includes('المنسق العام للمادة'),'missing support account must leave signature blank');
const ordinary=strings(ctx.N9({workspace:ws,subject:'التربية الإسلامية',supportLevel:false}));
assert.ok(ordinary.includes('المنسق العام للمادة'),'ordinary school report retains subject coordinator');
assert.ok(!ordinary.includes('منسق التربية الخاصة'),'ordinary footer label unchanged');
const html=S.reportFooterHTML(ws,'التربية الإسلامية','','',{supportLevel:true,supportCoordinatorName:'Ahmed'});
assert.ok(html.includes('منسق التربية الخاصة')&&html.includes('Ahmed'));
assert.ok(!html.includes('المنسق العام للمادة'),'HTML footer cannot fall back to subject coordinator for support');
