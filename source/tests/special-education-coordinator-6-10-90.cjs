const strings=node=>{
 if(node===null||node===undefined)return [];
 if(typeof node==='string')return [node];
 if(typeof node==='number')return [String(node)];
 if(Array.isArray(node))return node.flatMap(strings);
 if(typeof node==='object'&&node.props)return strings(node.props.children);
 return [];
};
const special=strings(ctx.N9({workspace:ws,subject:'التربية الإسلامية',supportLevel:true,supportCoordinatorName:'Ahmed'}));
assert.ok(special.includes('Ahmed'),'named special education coordinator appears in report');
