'use strict';
/* 6.10.90 — special education signature must always use the active scoped coordinator. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {ctx}=require('./harness.cjs').loadApp(),S=ctx.SR63;
assert.equal(typeof ctx.N9,'function','N9 report footer renderer is available');
const ws=ctx.zj();
